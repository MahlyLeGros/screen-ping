const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "..");
const privatePath = path.join(root, "deploy", "update-signing-private.pem");
const publicPath = path.join(root, "desktop", "main", "updatePublicKey.ts");
if (fs.existsSync(privatePath)) throw new Error(`Private key already exists: ${privatePath}`);
const { privateKey, publicKey } = crypto.generateKeyPairSync("ed25519");
fs.writeFileSync(privatePath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
const pem = publicKey.export({ type: "spki", format: "pem" }).toString();
fs.writeFileSync(publicPath, `// Generated by scripts/generate-update-keys.js\nexport const UPDATE_PUBLIC_KEY = ${JSON.stringify(pem)};\n`);
console.log(`Private key: ${privatePath}`);
console.log(`Public key:  ${publicPath}`);
